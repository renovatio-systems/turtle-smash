#!/usr/bin/env python3
"""Convert a PNG to a 320x240 RGB565 C array: png2rgb565.py in.png out.c symbol"""
import sys
from PIL import Image

W, H = 320, 240
src, dst, name = sys.argv[1:4]
im = Image.open(src).convert("RGB").resize((W, H), Image.BOX)
raw = im.tobytes()
px = [tuple(raw[i:i + 3]) for i in range(0, len(raw), 3)]
with open(dst, "w") as f:
    f.write(f"// Generated by tools/png2rgb565.py from {src.split('/')[-1]}. Do not edit.\n")
    f.write("#include <stdint.h>\n\n")
    f.write(f"const uint16_t {name}[{W} * {H}] = {{\n")
    for i in range(0, len(px), 12):
        f.write("    " + ",".join(f"0x{((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3):04X}"
                                  for r, g, b in px[i:i + 12]) + ",\n")
    f.write("};\n")
