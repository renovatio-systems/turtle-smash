#!/usr/bin/env python3
"""Builds the startup images from assets/title.png and assets/story.png:

  src/intro_images.c   title screen + the 4 story panels, as RGB565 arrays
  src/intro_images.h   extern declarations

story.png is a 2x2 grid (top-left, top-right, bottom-left, bottom-right) with a
white gutter between the panels, which is detected and cropped out so no white
edge survives the resize to the panel's 320x240.

usage: make_intro_assets.py assets/title.png assets/story.png src/
"""
import sys
from PIL import Image

W, H = 480, 320  # the panel size: intro art is shown unscaled

NAMES = ["story_top_left", "story_top_right", "story_bottom_left", "story_bottom_right"]


def rgb565(c):
    return ((c[0] & 0xF8) << 8) | ((c[1] & 0xFC) << 3) | (c[2] >> 3)


def is_pure_white(c, t=245):
    return c[0] >= t and c[1] >= t and c[2] >= t


def gutter_band(img, axis, margin=3):
    """Finds the near-white gutter line that splits `img` along `axis` ('x' splits
    left/right, 'y' splits top/bottom), searching near the middle. Returns the
    (start, end) range to cut out, padded by `margin` to clear antialiasing."""
    w, h = img.size
    px = img.load()
    size, window = (w, w // 6) if axis == "x" else (h, h // 6)
    center = size // 2

    def frac(i):
        if axis == "x":
            return sum(is_pure_white(px[i, y]) for y in range(0, h, 2)) / (h // 2)
        return sum(is_pure_white(px[x, i]) for x in range(0, w, 2)) / (w // 2)

    hits = [i for i in range(center - window, center + window) if frac(i) > 0.5]
    if not hits:
        return center, center  # no gutter found: cut nothing
    return max(0, min(hits) - margin), min(size, max(hits) + margin + 1)


def to_raw(img):
    im = img.convert("RGB").resize((W, H), Image.BOX)
    data = im.tobytes()
    return [rgb565(tuple(data[i:i + 3])) for i in range(0, W * H * 3, 3)]


def dump_array(f, name, raw):
    f.write(f"const uint16_t {name}[{W} * {H}] = {{\n")
    for i in range(0, len(raw), 12):
        f.write("    " + ",".join(f"0x{v:04X}" for v in raw[i:i + 12]) + ",\n")
    f.write("};\n\n")


title_src, story_src, outdir = sys.argv[1:4]

title = Image.open(title_src)
story = Image.open(story_src).convert("RGB")
sw, sh = story.size
gx0, gx1 = gutter_band(story, "x")
gy0, gy1 = gutter_band(story, "y")
quadrants = [
    story.crop((0, 0, gx0, gy0)),    # top-left
    story.crop((gx1, 0, sw, gy0)),   # top-right
    story.crop((0, gy1, gx0, sh)),   # bottom-left
    story.crop((gx1, gy1, sw, sh)),  # bottom-right
]

with open(f"{outdir}/intro_images.c", "w") as f:
    f.write("// Generated by tools/make_intro_assets.py. Do not edit.\n")
    f.write('#include "intro_images.h"\n\n')
    dump_array(f, "title_image", to_raw(title))
    for name, q in zip(NAMES, quadrants):
        dump_array(f, name, to_raw(q))

with open(f"{outdir}/intro_images.h", "w") as f:
    decls = "\n".join(f"extern const uint16_t {n}[{W} * {H}];" for n in ["title_image"] + NAMES)
    f.write(f"""// Generated by tools/make_intro_assets.py. Do not edit.
#ifndef INTRO_IMAGES_H
#define INTRO_IMAGES_H

#include <stdint.h>

{decls}

#endif
""")

print("title", W, "x", H, " story panels", len(NAMES))
